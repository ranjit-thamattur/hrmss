"""Generate docs/data-dictionary.md from the entity catalogue (services/hrms-core/backend/app/core/specs.py).

    python scripts/make_docs.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "hrms-core" / "backend"))
from app.core.specs import SPECS, SPECS_LIST  # noqa: E402

KIND = {"str": "text", "text": "long text", "email": "email", "enum": "one of", "int": "number", "year": "year", "decimal": "amount",
        "bool": "yes/no", "date": "date", "time": "HH:MM", "period": "YYYY-MM", "json": "JSON", "ref": "link to", "refs": "links to",
        "secret": "encrypted text", "secret_json": "encrypted JSON", "datetime": "date-time"}


def main() -> None:
    out = ["# Data dictionary", "", "GENERATED by `scripts/make_docs.py` from the entity catalogue - do not edit by hand.", "",
           "Every entity is versioned: `rid` (stable id), `valid_from` / `valid_to`, `is_active`, `created_by`, `created_at`, "
           "`change_reason`, `client_id` (from the login). Records are deactivated, never deleted.", "",
           "| # | Entity | API | Stage | Code field |", "|---|---|---|---|---|"]
    for s in SPECS_LIST:
        out.append(f"| {s.number} | {s.title} | `{s.path}` | {s.stage} | {s.code_field or '-'} |")
    for s in SPECS_LIST:
        out += ["", f"## {s.number}. {s.title}", "", s.help or "", "", f"API: `{s.path}`", "", "| Field | Type | Required | Notes |", "|---|---|---|---|"]
        for f in s.fields:
            t = KIND.get(f.kind, f.kind)
            if f.kind in ("ref", "refs"):
                t += f" {SPECS[f.ref].title.lower()}"
            if f.choices:
                t += ": " + ", ".join(f.choices)
            notes = []
            if f.readonly:
                notes.append("set by the system")
            if f.pattern:
                notes.append(f"format: {f.pattern}")
            if f.default is not None:
                notes.append(f"default {f.default}")
            if f.name == s.code_field:
                notes.append("unique per client, not case-sensitive")
            out.append(f"| `{f.name}` | {t} | {'yes' if f.required and f.default is None else ''} | {'; '.join(notes)} |")
        if s.unique_overlap:
            out.append("")
            out.append("No two active records with the same " + " / ".join(", ".join(k) for k in s.unique_overlap) + " may overlap in time.")
    (ROOT / "docs" / "data-dictionary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("docs/data-dictionary.md written")


if __name__ == "__main__":
    main()
