"""Field encryption, password hashing (local auth mode) and app tokens (local auth mode)."""
from __future__ import annotations

import base64
import hashlib
import hmac
import logging
import os
from datetime import datetime, timedelta, timezone

import jwt
from cryptography.fernet import Fernet, InvalidToken

from ..config import get_settings

log = logging.getLogger("hrms.security")
settings = get_settings()


def _fernet() -> Fernet:
    key = settings.field_encryption_key
    if not key:
        if settings.environment not in ("local", "test"):
            raise RuntimeError("FIELD_ENCRYPTION_KEY must be set outside local development")
        # local only: derive a stable key from the JWT secret so data survives restarts
        key = base64.urlsafe_b64encode(hashlib.sha256(settings.jwt_secret.encode()).digest()).decode()
    try:
        return Fernet(key.encode())
    except ValueError:
        # A secret that is not already a Fernet key (e.g. generated by AWS Secrets Manager): derive one from it.
        return Fernet(base64.urlsafe_b64encode(hashlib.sha256(key.encode()).digest()))


def encrypt(value: str | None) -> str | None:
    if not value:
        return None
    return _fernet().encrypt(value.encode()).decode()


def decrypt(value: str | None) -> str | None:
    if not value:
        return None
    try:
        return _fernet().decrypt(value.encode()).decode()
    except InvalidToken:
        log.error("Could not decrypt a field: wrong FIELD_ENCRYPTION_KEY?")
        return None


def hash_password(password: str) -> str:
    salt = os.urandom(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=2**14, r=8, p=1, dklen=32)
    return "scrypt$" + base64.b64encode(salt).decode() + "$" + base64.b64encode(digest).decode()


def verify_password(password: str, stored: str | None) -> bool:
    if not stored or not stored.startswith("scrypt$"):
        return False
    _, s, d = stored.split("$")
    digest = hashlib.scrypt(password.encode(), salt=base64.b64decode(s), n=2**14, r=8, p=1, dklen=32)
    return hmac.compare_digest(digest, base64.b64decode(d))


def password_ok(password: str) -> str | None:
    """Same rules as the Cognito pool: 8+ chars, upper, lower, digit."""
    if len(password) < 8:
        return "Password must have at least 8 characters"
    if not any(c.isupper() for c in password) or not any(c.islower() for c in password) or not any(c.isdigit() for c in password):
        return "Password needs an upper-case letter, a lower-case letter and a number"
    return None


def issue_local_token(email: str) -> str:
    exp = datetime.now(timezone.utc) + timedelta(minutes=settings.jwt_minutes)
    return jwt.encode({"sub": email, "email": email, "iss": "peak-hrms-local", "exp": exp}, settings.jwt_secret, algorithm="HS256")


def verify_local_token(token: str) -> dict:
    return jwt.decode(token, settings.jwt_secret, algorithms=["HS256"], issuer="peak-hrms-local")
