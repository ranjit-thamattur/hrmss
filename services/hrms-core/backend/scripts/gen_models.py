"""Generate app/models.py from the entity catalogue (app/core/specs.py).

    cd services/hrms-core/backend && python scripts/gen_models.py

The generated file is committed. tests/test_catalogue.py fails if it is out of date.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.core.specs import SPECS_LIST  # noqa: E402

COL = {
    "str": ("str", "String({n})"), "email": ("str", "String({n})"), "enum": ("str", "String(30)"), "time": ("str", "String(5)"),
    "period": ("str", "String(7)"), "text": ("str", "Text"), "int": ("int", "Integer"), "year": ("int", "Integer"),
    "decimal": ("Decimal", "Numeric(14, 2)"), "bool": ("bool", "Boolean"), "date": ("date", "Date"),
    "datetime": ("datetime", "DateTime(timezone=True)"), "json": ("Any", "JSON"), "refs": ("Any", "JSON"),
    "ref": ("int", "Integer"), "secret": ("str", "Text"), "secret_json": ("str", "Text"),
}

HEADER = '''"""Database tables. GENERATED by scripts/gen_models.py from app/core/specs.py: do not edit the generated
part by hand (the fixed tables at the top are hand-written).

Every catalogue entity is versioned: a row is one version of one record.
    rid          the record's stable id (same for all its versions)
    valid_from   first day this version applies;  valid_to  last day (empty = open)
    is_active    False = deactivated from valid_from (records are never deleted)
    client_id    the client the record belongs to (taken from the signed-in user, never from the request)
References between entities hold the target's rid (`*_rid`), so they survive new versions of the target.
"""
from __future__ import annotations

from datetime import date, datetime, timezone
from decimal import Decimal
from typing import Any

from sqlalchemy import JSON, Boolean, Date, DateTime, Integer, Numeric, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from .db import Base


def now() -> datetime:
    return datetime.now(timezone.utc)


# ---------------------------------------------------------------- fixed tables (hand-written)
class Client(Base):
    """1 Client (tenant): one per client, created and updated from the client YAML file."""
    __tablename__ = "clients"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    code: Mapped[str] = mapped_column(String(20), unique=True)
    name: Mapped[str] = mapped_column(String(200))
    country: Mapped[str] = mapped_column(String(2), default="IN")
    default_currency: Mapped[str] = mapped_column(String(3), default="INR")
    fy_start_month: Mapped[int] = mapped_column(Integer, default=4)
    aws_account_id: Mapped[str | None] = mapped_column(String(20))
    aws_region: Mapped[str | None] = mapped_column(String(30))
    domain: Mapped[str | None] = mapped_column(String(200))
    database_name: Mapped[str | None] = mapped_column(String(100))
    settings: Mapped[Any] = mapped_column(JSON, default=dict, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now)


class AppUser(Base):
    """16 User and role: one login per person (identity in Cognito), roles and data scope."""
    __tablename__ = "app_users"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    client_id: Mapped[int] = mapped_column(Integer, index=True)
    email: Mapped[str] = mapped_column(String(200), unique=True)
    display_name: Mapped[str] = mapped_column(String(200))
    person_rid: Mapped[int | None] = mapped_column(Integer, index=True)
    roles: Mapped[Any] = mapped_column(JSON, default=list, nullable=True)
    scope_entity_rids: Mapped[Any] = mapped_column(JSON, default=list, nullable=True)
    scope_location_rids: Mapped[Any] = mapped_column(JSON, default=list, nullable=True)
    scope_department_rids: Mapped[Any] = mapped_column(JSON, default=list, nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    identity_sub: Mapped[str | None] = mapped_column(String(200), index=True)
    password_hash: Mapped[str | None] = mapped_column(String(300))
    must_change_password: Mapped[bool] = mapped_column(Boolean, default=True)
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_by: Mapped[str] = mapped_column(String(200), default="system")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now)


class AppSetting(Base):
    """Small key-value store: Cognito ids after bootstrap, the client code this database belongs to."""
    __tablename__ = "app_settings"
    key: Mapped[str] = mapped_column(String(100), primary_key=True)
    value: Mapped[str] = mapped_column(Text)


class AuditLog(Base):
    """Append-only (a database trigger refuses UPDATE and DELETE on Postgres). Sensitive values are masked."""
    __tablename__ = "audit_log"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    client_id: Mapped[int] = mapped_column(Integer, index=True)
    at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now, index=True)
    actor: Mapped[str] = mapped_column(String(200))
    action: Mapped[str] = mapped_column(String(40))
    resource: Mapped[str] = mapped_column(String(60), index=True)
    rid: Mapped[int | None] = mapped_column(Integer, index=True)
    before: Mapped[Any] = mapped_column(JSON, nullable=True)
    after: Mapped[Any] = mapped_column(JSON, nullable=True)
    reason: Mapped[str | None] = mapped_column(String(300))
    approved_by: Mapped[str | None] = mapped_column(String(200))


class PendingChange(Base):
    """A backdated change waiting for approval (rule: controlled backdating)."""
    __tablename__ = "pending_changes"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    client_id: Mapped[int] = mapped_column(Integer, index=True)
    resource: Mapped[str] = mapped_column(String(60))
    rid: Mapped[int] = mapped_column(Integer)
    action: Mapped[str] = mapped_column(String(20))  # change | deactivate | reactivate | end
    payload: Mapped[Any] = mapped_column(JSON, nullable=True)
    effective_from: Mapped[date] = mapped_column(Date)
    reason: Mapped[str | None] = mapped_column(String(300))
    requested_by: Mapped[str] = mapped_column(String(200))
    requested_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now)
    status: Mapped[str] = mapped_column(String(20), default="pending", index=True)  # pending | approved | rejected | failed
    step: Mapped[int] = mapped_column(Integer, default=0)
    approvals: Mapped[Any] = mapped_column(JSON, default=list, nullable=True)
    decided_by: Mapped[str | None] = mapped_column(String(200))
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    note: Mapped[str | None] = mapped_column(String(300))


class NumberCounter(Base):
    """Next number of each number series (locked while a number is allocated)."""
    __tablename__ = "number_counters"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    client_id: Mapped[int] = mapped_column(Integer, index=True)
    series_rid: Mapped[int] = mapped_column(Integer)
    next_number: Mapped[int] = mapped_column(Integer)
    __table_args__ = (UniqueConstraint("client_id", "series_rid"),)


class NumberAllocation(Base):
    """Every number ever handed out; the unique key makes reuse impossible."""
    __tablename__ = "number_allocations"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    client_id: Mapped[int] = mapped_column(Integer)
    object: Mapped[str] = mapped_column(String(30))
    value: Mapped[str] = mapped_column(String(60))
    series_rid: Mapped[int] = mapped_column(Integer)
    allocated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now)
    allocated_by: Mapped[str] = mapped_column(String(200))
    __table_args__ = (UniqueConstraint("client_id", "object", "value"),)


# ---------------------------------------------------------------- catalogue entities (generated)
'''


def main() -> str:
    out = [HEADER]
    for s in SPECS_LIST:
        out.append(f"class {s.model}(Base):")
        out.append(f'    """{s.number} {s.title} (stage {s.stage})."""')
        out.append(f'    __tablename__ = "{s.table}"')
        out.append("    id: Mapped[int] = mapped_column(Integer, primary_key=True)")
        out.append("    rid: Mapped[int | None] = mapped_column(Integer, index=True)")
        out.append("    client_id: Mapped[int] = mapped_column(Integer, index=True)")
        out.append("    valid_from: Mapped[date] = mapped_column(Date)")
        out.append("    valid_to: Mapped[date | None] = mapped_column(Date)")
        out.append("    is_active: Mapped[bool] = mapped_column(Boolean, default=True)")
        out.append("    created_by: Mapped[str] = mapped_column(String(200))")
        out.append("    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=now)")
        out.append("    change_reason: Mapped[str | None] = mapped_column(String(300))")
        for f in s.fields:
            py, col = COL[f.kind]
            col = col.format(n=f.max_len)
            idx = ", index=True" if f.kind == "ref" else ""
            out.append(f"    {f.name}: Mapped[{py} | None] = mapped_column({col}{idx})" if py != "Any" else f"    {f.name}: Mapped[Any] = mapped_column({col}, nullable=True)")
        if s.dedupe_hash:
            out.append(f"    {s.dedupe_hash}_hash: Mapped[str | None] = mapped_column(String(64), index=True)")
        out.append("")
        out.append("")
    out.append("MODELS: dict[str, Any] = {")
    for s in SPECS_LIST:
        out.append(f'    "{s.key}": {s.model},')
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    target = ROOT / "app" / "models.py"
    text = main()
    if "--check" in sys.argv:
        sys.exit(0 if target.read_text() == text else "app/models.py is out of date: run python scripts/gen_models.py")
    target.write_text(text)
    print("wrote", target)
